/**
 * Generate a thin static share page at the repo root for each active
 * property: listing-<id>.html.
 *
 * Why these exist:
 *   Facebook / Messenger / WhatsApp / LinkedIn / X preview crawlers do not
 *   execute JavaScript. Without a crawler-visible static page per listing,
 *   every shared URL would show the homepage OG card regardless of which
 *   listing was linked. These pages expose per-listing <meta og:*>,
 *   <meta twitter:*>, <title>, <meta description>, and static JSON-LD
 *   (VacationRental + BreadcrumbList). Humans are redirected immediately
 *   into the SPA at /?listing=<id> via meta refresh + inline script.
 *
 * Output is always overwritten. These files ARE committed so local dev
 * reflects what production ships and diffs are reviewable.
 *
 * Usage: npm run generate-listing-pages (also runs in Deploy workflow).
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const {
    PROPERTIES,
    SEO_CONFIG,
    baseUrl,
    absoluteUrl,
    getListingCanonicalUrl,
    getListingRelativePath,
    generatePropertySEO,
    buildVacationRentalSchema,
    buildBreadcrumbSchema,
    serialize,
    safeJsonForScript
} = require('./lib/listing-schema.cjs');

const GENERATED_MARKER = '<!-- GENERATED by scripts/generate-listing-pages.cjs — do not edit by hand -->';

function escapeHtmlAttr(value) {
    return String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function escapeHtmlText(value) {
    return String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');
}

function buildPage(property) {
    const base = baseUrl();
    const canonical = getListingCanonicalUrl(property.id);
    const redirectTo = `/?listing=${encodeURIComponent(property.id)}`;
    const seo = generatePropertySEO(property);
    const ogImage = `${base}/images/og/listing-${encodeURIComponent(property.id)}.jpg`;
    const ogAlt = `${property.title} — ${property.location}. Book direct with ${SEO_CONFIG.siteName}.`;
    const siteTitle = `${property.title} | ${SEO_CONFIG.siteName}`;
    const description = seo.description;

    const vrJson = safeJsonForScript(serialize(buildVacationRentalSchema(property)));
    const bcJson = safeJsonForScript(serialize(buildBreadcrumbSchema(property)));

    // CSP here is the slim one used by 404/privacy/terms (no Leaflet, no
    // Web3Forms, no media.scurto.net). Kept in sync with other static pages.
    // Microsoft Clarity (www.clarity.ms + *.clarity.ms) allowlisted for session
    // recordings & heatmaps; runs cookieless via clarity("consent", false).
    const csp = "default-src 'self'; script-src 'self' 'unsafe-inline' https://static.cloudflareinsights.com https://*.clarity.ms; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data: https:; connect-src 'self' https://cloudflareinsights.com https://static.cloudflareinsights.com https://*.clarity.ms; base-uri 'self'; object-src 'none'";

    return `<!DOCTYPE html>
<html lang="en">
<head>
    ${GENERATED_MARKER}
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <meta http-equiv="Content-Security-Policy" content="${escapeHtmlAttr(csp)}">
    <meta name="referrer" content="strict-origin-when-cross-origin">
    <link rel="icon" href="favicon.svg" type="image/svg+xml">
    <title>${escapeHtmlText(siteTitle)}</title>
    <meta name="description" content="${escapeHtmlAttr(description)}">
    <meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">
    <link rel="canonical" href="${escapeHtmlAttr(canonical)}">
    <meta http-equiv="refresh" content="0;url=${escapeHtmlAttr(redirectTo)}">

    <meta property="og:type" content="website">
    <meta property="og:site_name" content="${escapeHtmlAttr(SEO_CONFIG.siteName)}">
    <meta property="og:locale" content="en_US">
    <meta property="og:title" content="${escapeHtmlAttr(property.title)}">
    <meta property="og:description" content="${escapeHtmlAttr(description)}">
    <meta property="og:image" content="${escapeHtmlAttr(ogImage)}">
    <meta property="og:image:width" content="1200">
    <meta property="og:image:height" content="630">
    <meta property="og:image:alt" content="${escapeHtmlAttr(ogAlt)}">
    <meta property="og:url" content="${escapeHtmlAttr(canonical)}">

    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="${escapeHtmlAttr(property.title)}">
    <meta name="twitter:description" content="${escapeHtmlAttr(description)}">
    <meta name="twitter:image" content="${escapeHtmlAttr(ogImage)}">
    <meta name="twitter:image:alt" content="${escapeHtmlAttr(ogAlt)}">

    <meta name="geo.region" content="US-FL">
    <meta name="geo.placename" content="${escapeHtmlAttr(seo.city)}">
    <meta name="author" content="${escapeHtmlAttr(SEO_CONFIG.siteName)}">

    <script type="application/ld+json" data-schema="listing-${property.id}">${vrJson}</script>
    <script type="application/ld+json" data-schema="breadcrumb-${property.id}">${bcJson}</script>

    <style>
        html, body { margin: 0; padding: 0; }
        body {
            font-family: 'Inter', 'Segoe UI', -apple-system, BlinkMacSystemFont, Arial, sans-serif;
            min-height: 100vh;
            display: flex;
            align-items: center;
            justify-content: center;
            background: #0f172a;
            color: #e2e8f0;
            text-align: center;
            padding: 2rem 1.25rem;
            line-height: 1.5;
        }
        main { max-width: 32rem; }
        h1 { font-size: 1.25rem; font-weight: 600; margin: 0 0 .5rem; color: #f8fafc; }
        p { margin: 0; color: #94a3b8; }
        a { color: #38bdf8; text-decoration: underline; text-underline-offset: 2px; }
        a:hover, a:focus { color: #7dd3fc; }
    </style>
</head>
<body>
    <main>
        <h1>Opening ${escapeHtmlText(property.title)}…</h1>
        <p>If you are not redirected automatically, <a href="${escapeHtmlAttr(redirectTo)}">view the listing</a>.</p>
    </main>
    <script>window.location.replace(${JSON.stringify(redirectTo)});</script>
    <!-- CF_BEACON_START -->
    <script defer src="https://static.cloudflareinsights.com/beacon.min.js" data-cf-beacon='{"token": "__CF_BEACON_TOKEN__"}'></script>
    <!-- CF_BEACON_END -->
    <!-- CLARITY_START -->
    <script>
        (function(c,l,a,r,i,t,y){
            c[a]=c[a]||function(){(c[a].q=c[a].q||[]).push(arguments)};
            t=l.createElement(r);t.async=1;t.src="https://www.clarity.ms/tag/"+i;
            y=l.getElementsByTagName(r)[0];y.parentNode.insertBefore(t,y);
        })(window, document, "clarity", "script", "__CLARITY_PROJECT_ID__");
        window.clarity && window.clarity("consent", false);
    </script>
    <!-- CLARITY_END -->
</body>
</html>
`;
}

function main() {
    if (!Array.isArray(PROPERTIES) || PROPERTIES.length === 0) {
        throw new Error('PROPERTIES missing or empty in config.js');
    }
    let count = 0;
    for (const p of PROPERTIES) {
        if (!p || typeof p.id === 'undefined') continue;
        const outPath = path.join(ROOT, `listing-${p.id}.html`);
        fs.writeFileSync(outPath, buildPage(p), 'utf8');
        count += 1;
        console.log(`  ${path.basename(outPath)}  (${p.title})`);
    }
    console.log(`Generated ${count} listing share page(s).`);
}

main();
